#include <cstring>
#include <filesystem>
#include <iostream>

#if defined (WIN32)
#include <windows.h>
#endif

#include "../common/swFile.h"
#include "../common/swIO.h"
#include "../common/swLog.h"
#include "../common/geometry/swMesh.h"
#include "../common/swMessage.h"
#include "../common/version.h"
#include "common/swSolverParam.h"
#include "models/swParent.h"

int main(int argc, char **argv)
{
    // -- Handle popups under Windows
#if defined (WIN32)
    SetErrorMode(SEM_FAILCRITICALERRORS | SEM_NOGPFAULTERRORBOX | SEM_NOOPENFILEERRORBOX);
#endif
    // == Handle popups under Windows
    
    //-- Descritpion of argv[]
    if (argc != 2)
    {
        std::cerr << "sw2dSolver should receive only 1 parameter";
        std::cerr << " and received " << argc - 1 << "." << std::endl;
        std::cerr << "  The parameter can be:" << std::endl;
        std::cerr << "    the path of the simulation folder (containing the 'input' folder)" << std::endl;
        std::cerr << "    -h or --help to show this message" << std::endl;
        std::cerr << "    -v or     --version to show the version of the program" << std::endl;
        exit(EXIT_FAILURE);
    }

    if ((strcmp(argv[1], "-h") == 0) || (strcmp(argv[1], "--help") == 0))
    {
        std::cout << std::endl << "DESCRIPTION :" << std::endl;
        std::cout << "  sw2dSolver is the computational engine that solves the governing equations. \n  It uses the files generated by sw2dConverter and sw2dZone as inputs, plus additional input files that can be manually edited." << std::endl;
        std::cout << std::endl << "PARAMETERS :" << std::endl;
        std::cout << "  sw2dSolver should receive exactly 1 parameter" << std::endl;
        std::cout << "  The parameter can be:" << std::endl;
        std::cout << "    the path of the simulation folder (containing the 'input' folder)" << std::endl;
        std::cout << "    -h or --help to show this message" << std::endl;
        std::cout << "    -v or --version to show the version of the program" << std::endl;
        std::cout << std::endl << "CREATED FILES :" << std::endl;
        std::cout << "  '" << swFile::output_boundary_fluxes_file << "' and '"
                           << swFile::output_hydro_map_file_root << "*.txt"
                           << swFile::output_transport_map_file_root << "*.txt" << std::endl;
        exit(EXIT_SUCCESS);
    }

    if ((strcmp(argv[1], "-v") == 0) || (strcmp(argv[1], "--version") == 0))
    {
        std::cout << "SW2D version " << sw2d_version << std::endl;
        exit(EXIT_SUCCESS);
    }
    //== Descritpion of argv[]

    //-- Check the user-defined option
    //---- Import from folder name
    const std::string user_defined_folder = argv[1];
    //------ Check existing folder
    if (std::filesystem::exists(user_defined_folder) == false)
    {
        std::cerr << "Folder " << user_defined_folder  << " does not exist" << std::endl;
        std::cerr << "Use option -h or --help to display option menu" << std::endl;
        return EXIT_FAILURE;
    }
    //====== Check existing folder

    //------ Reset simulation folder
    swIO *m_io = new swIO(user_defined_folder);
    m_io->createEmptyFolders(swFile::log_solver_file);
    swMessage::outfile = new std::ofstream(m_io->absolutePath(swFile::log_solver_file));
    //====== Reset simulation folder

    //------ write command line to log file
    std::string command_line = "";
    for (int i = 0; i < argc; ++i)
    {
        if (i == 0)
        {
            command_line = argv[i];
        }
        else
        {
            command_line = command_line + " " + argv[i];
        }
    }
    logInfo() << "Command line:" << command_line; 
    logInfo() << "Running version : " << sw2d_version;
    //====== write command line to log file
    //==== Import from folder name
    //== Check the user-defined option

    //-- Initialise solver
    logInfo() << "BEGIN INIT";
    //---- get common simulation parameters from input.solv
    swSolverParam *m_solver_param = new swSolverParam(m_io);
    if (m_solver_param->readParameters() != EXIT_SUCCESS)
    {
        logError() << "Error in m_solver_param->readParameters()";
        logFatal(__FILE__, __func__, __LINE__);
        return EXIT_FAILURE;
    }
    //==== get common simulation parameters from input.solv
    logInfo() << "END INIT" << std::endl;

    logInfo() << "BEGIN MESH BUILDING";
    //---- create the mesh
    logInfo() << "Creating the mesh";
    swMesh* m_mesh = new swMesh(m_io);
    logEmpt() << "        ...done";
    if (m_mesh->build() != EXIT_SUCCESS)
    {
        logError() << "Error while building mesh";
        logFatal(__FILE__, __func__, __LINE__);
    }
    if (m_solver_param->getHasQsection() == true)
    {
        logInfo() << "Reading q sections";
        if (m_mesh->readQSections() != EXIT_SUCCESS)
        {
            logError() << "Error while reading qsections file :" << swFile::input_qsection_file;
            logFatal(__FILE__, __func__, __LINE__);
        }
        logEmpt() << "...done";
    }
    //==== create the mesh
    logInfo() << "END MESH BUILDING" << std::endl;

    //---- create the model
    logInfo() << "BEGIN MODEL BUILDING";
    logInfo() << "Hyperbolic model creation";
    swParent *m_model = swParent::create(m_solver_param, m_io);
    logInfo() << "...done";
    logInfo() << "END MODEL BUILDING" << std::endl;
    //==== create the model

    //-- Empty output folder if new simulation (not hotstart)
    if (m_solver_param->getHotstart() == false)
    {
        m_io->createEmptyOutputFolder(true);
    }
    //== Empty output folder if new simulation (not hotstart)

    //---- initialize the model
    ///-- Import attributes from solver_param
    m_model->importAttributesFromSolverParam(m_solver_param);
    //==  Import attributes from solver_param
    logInfo() << "BEGIN MODEL INITIALIZATION";
    if (m_model->init(m_mesh) != EXIT_SUCCESS)
    {
        logError() << "Error while initialising the model";
        return EXIT_FAILURE;
    }
    logInfo() << "END MODEL INITIALIZATION" << std::endl;
    //==== initialize the models
    //== Initialise solver

    ///-- Kill solver_param & mesh
    delete m_solver_param;
    delete m_mesh;
    //==  Kill solver_param & mesh
    
    

    //-- Run the timeloop
    logInfo() << "BEGIN MODEL COMPUTATION";
    if (m_model->execute() != EXIT_SUCCESS)
    {
        logError() << "Error while initialising the model";
        return EXIT_FAILURE;
    }
    logInfo() << "END MODEL COMPUTATION" << std::endl;

    m_model->displayBiblio();

    logExit() << " Done";
    logEmpt() << "Solver ran with " << swMessage::nb_warn << " warning(s)";

    swMessage::finalizeLog();

    return 0;
}